const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source=fs.readFileSync('index.html','utf8').match(/<script>([\s\S]*?)<\/script>/)[1];
const core=source.split('// <core>')[1].split('// </core>')[0];
const timelines='function tlHtml('+source.split('function tlHtml(')[1].split('const MQ_ICONS =')[0];
const cards=source.slice(source.indexOf('function comparisonTrack('),source.indexOf('// Update only changed cards'));
const api=vm.runInNewContext(core+timelines+cards+'\n;({subtractIntervals,compareQueues,comparisonCard})');
const plain=x=>JSON.parse(JSON.stringify(x));
const diff=(a,b)=>api.compareQueues(new Map(a),new Map(b))[0];
assert.deepEqual(plain(api.subtractIntervals([[600,900]],[[660,900]])),[[600,660]]);
assert.deepEqual(plain(api.subtractIntervals([[60,240]],[[90,120],[150,180]])),[[60,90],[120,150],[180,240]]);
assert.deepEqual(plain(api.subtractIntervals([[60,180],[120,240]],[[0,90],[210,1440]])),[[90,210]]);
assert.deepEqual(plain(api.subtractIntervals([[-10,20],[1430,1500]],[])),[[0,20],[1430,1440]]);
assert.equal(diff([['1.1',[[0,60],[60,120]]]],[['1.1',[[0,120]]]]).status,'same');
const moved=diff([['1.1',[[600,900]]]],[['1.1',[[660,960]]]]);
assert.deepEqual(plain(moved.removedIv),[[600,660]]);
assert.deepEqual(plain(moved.addedIv),[[900,960]]);
assert.equal(moved.ta,moved.tb);
assert.equal(moved.status,'changed');
assert.equal(diff([['1.1',[]]],[['1.1',[]]]).status,'same');
assert.equal(diff([],[['1.1',[]]]).status,'new');
assert.equal(diff([['1.1',[]]],[]).status,'gone');
const input=[[10,100],[80,200]], before=JSON.stringify(input);
api.subtractIntervals(input,[[50,60]]);
assert.equal(JSON.stringify(input),before,'do not mutate schedule inputs');
const oldQ=new Map([['1.1',[[600,900]]]]),newQ=new Map([['1.1',[[660,960]]]]);
assert.match(api.comparisonCard(moved,oldQ,newQ),/Длительность прежняя, время изменилось/);
const gone=api.compareQueues(oldQ,new Map())[0];
const missing=api.comparisonCard(gone,oldQ,new Map());
assert.match(missing,/Нет данных для этой очереди/);
assert.doesNotMatch(missing,/меньше без света/,'a missing queue is not zero outages');
const named=new Map([['<script>',[[60,120]]]]);
assert.doesNotMatch(api.comparisonCard(api.compareQueues(named,named)[0],named,named),/<script>/);
console.log('Comparison interval and rendering tests passed');
